static gint failed;

#define CHECK(what) \
  do { if (!(what)) { printf ("line %d: %s\n", __LINE__, #what); failed++; } } while (0)

/* The file gives the pixels, of that width and height. */
static void
gives (const gchar *name, const guchar *png, gsize length,
       gint want_width, gint want_height, const guchar *want)
{
  GError *error = NULL;
  gint width = 0, height = 0;
  guchar *pixels = gdk_png_load_from_data (png, length, &width, &height, &error);

  if (!pixels || error || width != want_width || height != want_height ||
      memcmp (pixels, want, want_width * want_height * 4) != 0)
    {
      printf ("%s: %s\n", name, error ? error->message : "not the pixels it should give");
      failed++;
    }
  g_clear_error (&error);
  g_free (pixels);
}

/* With straight alpha the file gives those pixels, if any are given
 * to look for; and they are, each colour multiplied by its alpha, the
 * pixels it gives without.
 */
static void
gives_straight (const gchar *name, const guchar *png, gsize length, const guchar *want)
{
  GError *error = NULL;
  gint width = 0, height = 0, w = 0, h = 0, i;
  guchar *straight = gdk_png_load_from_data_straight (png, length, &width, &height, &error);
  guchar *pixels = gdk_png_load_from_data (png, length, &w, &h, NULL);

  if (!straight || error || !pixels || width != w || height != h ||
      (want && memcmp (straight, want, width * height * 4) != 0))
    {
      printf ("%s, straight: %s\n", name, error ? error->message : "not the pixels it should give");
      failed++;
    }
  else
    for (i = 0; i < width * height * 4; i += 4)
      if (straight[i + 3] != pixels[i + 3] ||
          (straight[i] * straight[i + 3] + 127) / 255 != pixels[i] ||
          (straight[i + 1] * straight[i + 3] + 127) / 255 != pixels[i + 1] ||
          (straight[i + 2] * straight[i + 3] + 127) / 255 != pixels[i + 2])
        {
          printf ("%s, straight: pixel %d is not the other one's\n", name, i / 4);
          failed++;
          break;
        }
  g_clear_error (&error);
  g_free (straight);
  g_free (pixels);
}

/* The data is refused, with that error. */
static void
refused (const gchar *name, const guchar *png, gsize length, gint code)
{
  GError *error = NULL;
  gint width = 7, height = 7;
  guchar *pixels = gdk_png_load_from_data (png, length, &width, &height, &error);

  if (pixels || !error || error->domain != GDK_PNG_ERROR || error->code != code)
    {
      printf ("%s: %s\n", name, pixels ? "was read" : error ? error->message : "no error was set");
      failed++;
    }
  g_clear_error (&error);
  g_free (pixels);

  /* and the same asked for with straight alpha */
  pixels = gdk_png_load_from_data_straight (png, length, &width, &height, &error);
  if (pixels || !error || error->domain != GDK_PNG_ERROR || error->code != code)
    {
      printf ("%s, straight: %s\n", name, pixels ? "was read" : error ? error->message : "no error was set");
      failed++;
    }
  g_clear_error (&error);
  g_free (pixels);
}

int
main (void)
{
  const gchar *file = "testpng.tmp";
  GError *error = NULL;
  guchar damaged[sizeof rgba_png], *pixels;
  gint width, height;
  gsize i;

  gives ("colours with alpha", rgba_png, sizeof rgba_png, 3, 2, rgba_pixels);
  gives ("a palette", palette_png, sizeof palette_png, 2, 2, palette_pixels);
  gives ("grey of sixteen bits", grey16_png, sizeof grey16_png, 2, 1, grey16_pixels);
  gives ("interlaced", interlaced_png, sizeof interlaced_png, 5, 5, interlaced_pixels);

  gives_straight ("colours with alpha", rgba_png, sizeof rgba_png, rgba_straight);
  gives_straight ("a palette", palette_png, sizeof palette_png, palette_straight);
  gives_straight ("grey of sixteen bits", grey16_png, sizeof grey16_png, NULL);
  gives_straight ("interlaced", interlaced_png, sizeof interlaced_png, NULL);

  refused ("too wide and too high", huge_png, sizeof huge_png, GDK_PNG_ERROR_TOO_LARGE);
  refused ("too many pixels", many_png, sizeof many_png, GDK_PNG_ERROR_TOO_LARGE);
  refused ("not a picture", (const guchar *) "GIF89a, it says", 15, GDK_PNG_ERROR_FAILED);
  refused ("nothing", (const guchar *) "", 0, GDK_PNG_ERROR_FAILED);

  /* cut short at every length, to where only the twelve bytes that
   * mark the end are gone, which libpng does without; and with each
   * byte in turn wrong: read or refused, and never anything else */
  for (i = 0; i < sizeof rgba_png - 12; i++)
    refused ("cut short", rgba_png, i, GDK_PNG_ERROR_FAILED);
  for (i = 0; i < sizeof rgba_png; i++)
    {
      memcpy (damaged, rgba_png, sizeof rgba_png);
      damaged[i] ^= 0x55;
      pixels = gdk_png_load_from_data (damaged, sizeof damaged, &width, &height, &error);
      CHECK ((pixels != NULL) != (error != NULL));
      g_clear_error (&error);
      g_free (pixels);
    }

  /* from a file, and from none */
  CHECK (g_file_set_contents (file, (const gchar *) palette_png, sizeof palette_png, NULL));
  pixels = gdk_png_load (file, &width, &height, &error);
  CHECK (pixels && !error && width == 2 && height == 2 &&
         memcmp (pixels, palette_pixels, sizeof palette_pixels) == 0);
  g_free (pixels);
  pixels = gdk_png_load_straight (file, &width, &height, &error);
  CHECK (pixels && !error && width == 2 && height == 2 &&
         memcmp (pixels, palette_straight, sizeof palette_straight) == 0);
  g_free (pixels);
  unlink (file);
  pixels = gdk_png_load (file, &width, &height, &error);
  CHECK (!pixels && error && error->domain == G_FILE_ERROR && error->code == G_FILE_ERROR_NOENT);
  g_clear_error (&error);
  pixels = gdk_png_load_straight (file, &width, &height, &error);
  CHECK (!pixels && error && error->domain == G_FILE_ERROR && error->code == G_FILE_ERROR_NOENT);
  g_clear_error (&error);

  if (failed)
    printf ("%d failed\n", failed);

  return failed != 0;
}
